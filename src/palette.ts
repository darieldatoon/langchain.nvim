export function roles(p: Palette, variant: Variant): Roles {
  const c = p.color;
  const bg = c('--bg-surface-level-1');
  const tint = (token: TokenName, alpha: number) =>
    over(p.alpha(token, alpha), bg);
  return {
    bg,
    bg_sidebar: c('--bg-surface-level-2'),
    bg_float: c('--bg-elevated'),
    bg_highlight: c('--bg-surface-level-2'),
    bg_raised: c('--bg-surface-level-3'),
    bg_selected: c('--bg-selected'),
    bg_visual: tint('--bg-brand', 0.25),
    bg_search: tint('--bg-warning-strong', 0.3),
    bg_search_current: tint('--bg-warning-strong', 0.45),
    border: c('--border-subtle'),
    border_strong: c('--border-default'),
    fg: c('--syntax-plain'),
    fg_ui: c('--text-secondary'),
    fg_strong: c('--text-primary'),
    fg_muted: c('--text-tertiary'),
    fg_subtle: c('--text-quaternary'),
    fg_disabled: c('--text-disabled'),
    brand: c('--icon-brand'),
    brand_fill: c('--bg-brand'),
    on_brand: c('--text-brand-on-fill'),
    link: c('--text-link'),
    comment: c('--syntax-comment'),
    keyword: c('--syntax-keyword'),
    operator: c('--syntax-operator'),
    string: c('--syntax-string'),
    number: c('--syntax-number'),
    constant: c('--syntax-constant'),
    func: c('--syntax-function'),
    type: c('--syntax-type'),
    property: c('--syntax-property'),
    tag: c('--syntax-tag'),
    decorator: c('--syntax-decorator'),
    error: c('--icon-error'),
    warning: c('--icon-warning'),
    info: c('--icon-brand'),
    hint: c('--syntax-type'),
    ok: c('--icon-success'),
    git_add: c('--bg-success-strong'),
    git_change: c('--bg-brand'),
    git_delete: c('--bg-error-strong'),
    diff_add: tint('--bg-success-strong', 0.15),
    diff_change: tint('--bg-brand', 0.08),
    diff_delete: tint('--bg-error-strong', 0.15),
    diff_text: tint('--bg-brand', 0.22),
    terminal: ansi[variant].map(c),
  };
}

/** A Lua module returning the roles table. */
export function renderLua(r: Roles, variant: Variant): string {
  const lines = Object.entries(r).map(([key, value]) =>
    Array.isArray(value)
      ? `  ${key} = {\n${value.map((v) => `    "${v}",`).join('\n')}\n  },`
      : `  ${key} = "${value}",`
  );
  return [
    `-- LangChain ${variant === 'light' ? 'Light' : 'Dark'} palette.`,
    '-- Generated by src/generate.ts from @langchain/macaw-tokens. Do not edit.',
    'return {',
    ...lines,
    '}',
    '',
  ].join('\n');
}
